#!/usr/bin/env node
// One-off: extract hero-demo frames from a probe MP4, upload to fal storage,
// and write src/lib/demo-frames.ts with the URL array. The homepage hero uses
// these pre-extracted frames so it loads instantly (no server-side ffmpeg on
// page render). Frames are scaled to 720w JPEGs (~30-40 KB each) to keep the
// hero payload ~2 MB.
//
// Usage: node scripts/extract-demo-frames.mjs [videoUrl]

import { readFileSync, writeFileSync, existsSync, mkdtempSync, readdirSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

if (existsSync(".env.local")) {
  for (const line of readFileSync(".env.local", "utf8").split("\n")) {
    const m = line.match(/^([A-Z_]+)=(.*)$/);
    if (m && !process.env[m[1]]) process.env[m[1]] = m[2].replace(/^["']|["']$/g, "");
  }
}
const FAL_KEY = process.env.FAL_KEY ?? process.env.FAL_API_TOKEN;
if (!FAL_KEY) { console.error("FAL_KEY not set"); process.exit(1); }

const VIDEO_URL = process.argv[2] ?? "https://v3b.fal.media/files/b/0aa11072/BRRQEH4QnEFQ0APQ62uwg_output.mp4";
const FRAME_COUNT = 60;
const DURATION = 10;

const { fal } = await import("@fal-ai/client");
fal.config({ credentials: FAL_KEY });

const ffmpegInstaller = (await import("@ffmpeg-installer/ffmpeg")).default;
const fluent = (await import("fluent-ffmpeg")).default;
fluent.setFfmpegPath(ffmpegInstaller.path);

console.log("[demo-frames] downloading video…");
const res = await fetch(VIDEO_URL);
const bytes = Buffer.from(await res.arrayBuffer());
const tmp = mkdtempSync(join(tmpdir(), "spinr-demo-"));
writeFileSync(join(tmp, "in.mp4"), bytes);

console.log("[demo-frames] extracting", FRAME_COUNT, "frames at 720w…");
await new Promise((resolve, reject) => {
  fluent(join(tmp, "in.mp4"))
    .outputOptions([
      "-vf", `fps=${(FRAME_COUNT / DURATION).toFixed(4)},scale=720:-2`,
      "-frames:v", String(FRAME_COUNT),
      "-q:v", "4",
    ])
    .output(join(tmp, "f%03d.jpg"))
    .on("end", resolve)
    .on("error", reject)
    .run();
});

const files = readdirSync(tmp).filter((f) => f.endsWith(".jpg")).sort();
console.log("[demo-frames] uploading", files.length, "frames to fal storage…");
const urls = await Promise.all(
  files.map(async (name) => {
    const buf = readFileSync(join(tmp, name));
    return fal.storage.upload(new Blob([new Uint8Array(buf)], { type: "image/jpeg" }));
  }),
);
rmSync(tmp, { recursive: true, force: true });

const ts = `// Pre-extracted demo spin frames for the homepage hero.
// Generated by scripts/extract-demo-frames.mjs — do not edit by hand.
// Source video: ${VIDEO_URL}
export const DEMO_SPIN_FRAMES: string[] = ${JSON.stringify(urls, null, 2)};
`;
writeFileSync("src/lib/demo-frames.ts", ts);
console.log(`[demo-frames] ✅ wrote src/lib/demo-frames.ts with ${urls.length} frames`);
console.log(`[demo-frames] first: ${urls[0]}`);
